const path = require('path');
const fs = require('fs');
const REPO = path.resolve(__dirname, '..', '..');
const { chromium } = require(path.join(REPO, 'node_modules', '@playwright/test'));
const { startDemoServer } = require(path.join(REPO, 'tests', 'helpers', 'start-demo-server.js'));
const { RELEASES } = require(path.join(REPO, 'lib', 'release-notes.js'));
(async () => {
    const server = await startDemoServer();
    const browser = await chromium.launch({ channel: 'msedge', headless: true });
    const context = await browser.newContext({ baseURL: server.baseURL, viewport: { width: 375, height: 740 }, serviceWorkers: 'block' });
    await context.request.post('/api/login', { data: { username: 'e2e', password: 'e2e' } });
    const page = await context.newPage();
    const GIF = fs.readFileSync(path.join(REPO, 'public', 'demo-gifs', 'brawo.gif'));
    await page.route('https://static*.klipy.com/**', r => r.fulfill({ contentType: 'image/gif', body: GIF }));
    // the page as a KLIPY server would list it
    const all = RELEASES;
    await page.route('**/api/releases', r => r.fulfill({ json: { releases: all } }));
    await page.route('**/api/version', async r => { const resp = await r.fetch(); const j = await resp.json(); j.release = all[0]; await r.fulfill({ response: resp, json: j }); });
    await page.addInitScript(() => { localStorage.setItem('app_version', 'old'); });
    await page.goto('/wiadomosci', { waitUntil: 'load' });
    await page.waitForSelector('#updateBanner img');
    await page.waitForTimeout(1200);
    await page.screenshot({ path: path.join(__dirname, '_s1.png') });
    await page.goto('/nowosci', { waitUntil: 'load' });
    await page.waitForSelector('.release-card');
    await page.waitForTimeout(800);
    await page.screenshot({ path: path.join(__dirname, '_s2.png'), fullPage: false });
    await browser.close();
    await server.stop().catch(() => {});
    process.exit(0);
})();
